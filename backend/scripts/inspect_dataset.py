"""Create a non-destructive manifest of class folders in the supplied image corpus."""
from __future__ import annotations
import hashlib, json
from collections import Counter
from datetime import date
from pathlib import Path
from PIL import Image

ROOT=Path(__file__).resolve().parents[2]; DATA=ROOT/'datasets'; OUT=DATA/'reports'; OUT.mkdir(exist_ok=True)
entries=[]
for base in [DATA/'MangoLeafBD Dataset']:
    if not base.exists(): continue
    for folder in sorted(x for x in base.iterdir() if x.is_dir()):
        files=[p for p in folder.rglob('*') if p.suffix.lower() in {'.jpg','.jpeg','.png'}]
        corrupt=0
        for f in files[:100]:
            try:
                with Image.open(f) as im: im.verify()
            except Exception: corrupt+=1
        entries.append({'source':str(folder.relative_to(DATA)),'label':folder.name,'image_count':len(files),'sample_checked':min(100,len(files)),'invalid_in_sample':corrupt})
manifest={'generated_on':date.today().isoformat(),'purpose':'Image-only baseline discovery. No environmental pairing is implied.','classes':entries,'notes':['Original datasets were not altered.','Environmental/fusion training requires timestamp-aligned real observations and should not be synthesized from these images.']}
(OUT/'dataset_manifest.json').write_text(json.dumps(manifest,indent=2),encoding='utf-8')
(OUT/'README.md').write_text('# Dataset reports\n\n`dataset_manifest.json` is generated by `backend/scripts/inspect_dataset.py`. It records only discovered class folders and sample corruption checks. It is not a license, provenance record, or performance report.\n',encoding='utf-8')
print(json.dumps(manifest,indent=2))
